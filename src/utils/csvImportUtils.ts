/**
 * Robust CSV/TSV tokenizer that handles double quotes, escaped quotes, and multiple delimiters
 */
export function tokenizeCsvLine(line: string, delimiter: string = ','): string[] {
  const result: string[] = [];
  let current = '';
  let inQuotes = false;
  
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    const nextChar = line[i + 1];

    if (char === '"') {
      if (inQuotes && nextChar === '"') {
        // Escaped double quote inside quotes
        current += '"';
        i++;
      } else {
        // Toggle quote state
        inQuotes = !inQuotes;
      }
    } else if (char === delimiter && !inQuotes) {
      result.push(cleanToken(current));
      current = '';
    } else {
      current += char;
    }
  }
  
  result.push(cleanToken(current));
  return result;
}

/**
 * Trims and strips any enclosing quotes from a token
 */
export function cleanToken(token: string): string {
  let s = token.trim();
  if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) {
    s = s.slice(1, -1).trim();
  }
  return s;
}

/**
 * Expands scientific notation (e.g. 8.63E+14 or 1.11E+11) frequently generated by Excel
 * for large numbers such as Barcodes and IMEIs into full integer digit strings.
 */
export function expandScientificNotation(val: string): string {
  if (!val) return '';
  const trimmed = val.trim();
  // Matches e.g. 8.62675065232361E+14, 1.11E+11, 3.6e+14
  if (/^[+-]?\d+(?:\.\d+)?[eE][+-]?\d+$/.test(trimmed)) {
    try {
      const num = Number(trimmed);
      if (!isNaN(num) && isFinite(num)) {
        return BigInt(Math.round(num)).toString();
      }
    } catch {
      return trimmed;
    }
  }
  return trimmed;
}

/**
 * Detects the most probable delimiter for tabular text (comma, tab, semicolon, pipe)
 */
export function detectDelimiter(text: string): string {
  const firstLines = text.split(/\r?\n/).filter(l => l.trim().length > 0).slice(0, 5);
  if (firstLines.length === 0) return ',';

  const counts: Record<string, number> = { '\t': 0, ',': 0, ';': 0, '|': 0 };

  firstLines.forEach(line => {
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        inQuotes = !inQuotes;
      } else if (!inQuotes && counts[char] !== undefined) {
        counts[char]++;
      }
    }
  });

  let bestDelimiter = ',';
  let maxCount = -1;

  // Prefer tabs for TSV (Excel/Google Sheets copy paste) if prevalent
  for (const [del, count] of Object.entries(counts)) {
    if (count > maxCount && count > 0) {
      maxCount = count;
      bestDelimiter = del;
    }
  }

  return bestDelimiter;
}

/**
 * Normalizes category string to valid ProductCategory enum value
 */
export function normalizeCategory(input?: string, contextName?: string): ProductCategory {
  if (!input || input === '-' || input.toLowerCase() === 'none') {
    if (contextName) {
      const lower = contextName.toLowerCase();
      if (lower.includes('cook') || lower.includes('pot') || lower.includes('pan') || lower.includes('kettle') || lower.includes('blender') || lower.includes('fryer') || lower.includes('wok') || lower.includes('rice cooker') || lower.includes('ဟင်းချက်အိုး')) {
        return 'cookware';
      }
      if (lower.includes('case') || lower.includes('cover') || lower.includes('charger') || lower.includes('cable') || lower.includes('power bank') || lower.includes('watch') || lower.includes('earbuds') || lower.includes('audio') || lower.includes('fan')) {
        return 'accessories_gadgets';
      }
      if (lower.includes('sim') || lower.includes('esim') || lower.includes('topup') || lower.includes('top-up')) {
        return 'sim_cards';
      }
      if (lower.includes('used') || lower.includes('secondhand') || lower.includes('preowned')) {
        return 'pre_owned_phones';
      }
    }
    return 'brand_new_phones';
  }

  const clean = input.toLowerCase().trim();

  // Direct matches to labels & enums
  if (clean === 'brand_new_phones' || clean === 'new_phones' || clean.includes('brand new phone') || clean === 'smartphones') {
    return 'brand_new_phones';
  }
  if (clean === 'pre_owned_phones' || clean === 'used_phones' || clean.includes('pre-owned') || clean.includes('preowned') || clean.includes('used phone') || clean.includes('secondhand')) {
    return 'pre_owned_phones';
  }
  if (clean === 'accessories_gadgets' || clean === 'accessories' || clean === 'gadgets' || clean.includes('accessori') || clean.includes('gadget') || clean.includes('charger') || clean.includes('cable')) {
    return 'accessories_gadgets';
  }
  if (clean === 'cookware' || clean.includes('cook') || clean.includes('kitchen') || clean.includes('ဟင်းချက်အိုး')) {
    return 'cookware';
  }
  if (clean === 'sim_cards' || clean === 'sim_topup' || clean.includes('sim')) {
    return 'sim_cards';
  }
  if (clean === 'spare_parts' || clean.includes('spare') || clean.includes('part') || clean.includes('screen') || clean.includes('lcd')) {
    return 'spare_parts';
  }

  const noSpecial = clean.replace(/[^a-z0-9]/g, '');
  if (noSpecial.includes('cook')) return 'cookware';
  if (noSpecial.includes('access') || noSpecial.includes('gadget')) return 'accessories_gadgets';
  if (noSpecial.includes('used') || noSpecial.includes('second')) return 'pre_owned_phones';
  if (noSpecial.includes('phone') || noSpecial.includes('mobile')) return 'brand_new_phones';

  return 'brand_new_phones';
}

/**
 * Normalizes condition string to DeviceCondition enum value
 */
export function normalizeCondition(input?: string): DeviceCondition {
  if (!input || input === '-' || input.toLowerCase() === 'none') return 'brand_new';
  const clean = input.toLowerCase().replace(/[^a-z0-9+]/g, '');

  if (clean.includes('aplus') || clean.includes('a+') || clean.includes('gradeaplus') || clean.includes('likenew') || clean.includes('99')) {
    return 'used_grade_a_plus';
  }
  if (clean.includes('gradea') || clean.includes('useda') || clean.includes('excellent') || clean.includes('95')) {
    return 'used_grade_a';
  }
  if (clean.includes('gradeb') || clean.includes('usedb') || clean.includes('good') || clean.includes('90')) {
    return 'used_grade_b';
  }
  if (clean.includes('gradec') || clean.includes('usedc') || clean.includes('fair') || clean.includes('85')) {
    return 'used_grade_c';
  }
  if (clean.includes('used') || clean.includes('second') || clean.includes('preowned')) {
    return 'used_grade_a';
  }

  return 'brand_new';
}

/**
 * Cleans currency/number strings (e.g. "3,500,000 Ks" -> 3500000, "11.3%" -> 11.3)
 */
export function parseCleanNumber(val?: string | number, fallback: number = 0): number {
  if (val === undefined || val === null) return fallback;
  if (typeof val === 'number') return isNaN(val) ? fallback : val;
  
  const str = String(val).trim();
  if (str === '-' || str === 'none' || str === 'n/a') return fallback;

  // Handle scientific notation numbers like 1.5E+11
  const expanded = expandScientificNotation(str);
  const cleaned = expanded.replace(/[^0-9.-]/g, '');
  const num = parseFloat(cleaned);
  return isNaN(num) ? fallback : num;
}

